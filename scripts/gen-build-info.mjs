// Generated at prebuild — writes the current YYYYMMDD-HHMM stamp
// (in America/Los_Angeles since this is a hyperlocal Martinez app)
// into src/lib/build-info.ts. The footer reads BUILD_STAMP and shows
// it in the bottom-right corner of every page.
//
// Run automatically via `npm run prebuild`. Safe to invoke manually.
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';

const now = new Date();
const fmt = new Intl.DateTimeFormat('en-CA', {
  timeZone: 'America/Los_Angeles',
  year: 'numeric', month: '2-digit', day: '2-digit',
  hour: '2-digit', minute: '2-digit', hour12: false,
});
const parts = Object.fromEntries(fmt.formatToParts(now).map((p) => [p.type, p.value]));
// en-CA spits out 24h with "24" for midnight — normalize to "00".
const hh = parts.hour === '24' ? '00' : parts.hour;
const stamp = `${parts.year}${parts.month}${parts.day}-${hh}${parts.minute}`;

const code = `// AUTO-GENERATED by scripts/gen-build-info.mjs at prebuild.
// Do not edit by hand — value reflects the most recent build/deploy.
export const BUILD_STAMP = '${stamp}';
export const BUILD_ISO = '${now.toISOString()}';
`;

const out = 'src/lib/build-info.ts';
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, code, 'utf8');
console.log(`[build-info] wrote ${out} -> ${stamp}`);
